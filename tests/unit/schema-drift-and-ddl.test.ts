import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

describe('Go-First DDL & sqlc Baseline Integrity', () => {
  const rootDir = path.resolve(__dirname, '../..');
  const ddlPath = path.join(rootDir, 'services/worker-sidecar/migrations/000001_baseline.sql');
  const sqlcConfigPath = path.join(rootDir, 'services/worker-sidecar/sqlc.yaml');
  const generatedCreditsPath = path.join(rootDir, 'services/worker-sidecar/internal/platform/db/credits.sql.go');
  const generatedUsersPath = path.join(rootDir, 'services/worker-sidecar/internal/platform/db/users.sql.go');

  it('should have 000001_baseline.sql with all tables and enums', () => {
    expect(fs.existsSync(ddlPath)).toBe(true);
    const content = fs.readFileSync(ddlPath, 'utf8');

    const tableMatches = content.match(/CREATE\s+TABLE\s+"([^"]+)"/g) || [];
    const enumMatches = content.match(/CREATE\s+TYPE\s+"([^"]+)"/g) || [];

    expect(tableMatches.length).toBeGreaterThanOrEqual(60);
    expect(enumMatches.length).toBeGreaterThanOrEqual(3);

    // Verify key tables exist in DDL
    expect(content).toContain('CREATE TABLE "User"');
    expect(content).toContain('CREATE TABLE "SavedRepo"');
    expect(content).toContain('CREATE TABLE "Repository"');
    expect(content).toContain('CREATE TABLE "CreditGrantLedger"');
  });

  it('should have sqlc configuration and generated Go files', () => {
    expect(fs.existsSync(sqlcConfigPath)).toBe(true);
    expect(fs.existsSync(generatedCreditsPath)).toBe(true);
    expect(fs.existsSync(generatedUsersPath)).toBe(true);

    const creditsContent = fs.readFileSync(generatedCreditsPath, 'utf8');
    expect(creditsContent).toContain('Code generated by sqlc');
    expect(creditsContent).toContain('GetCreditGrantsByUserID');

    const usersContent = fs.readFileSync(generatedUsersPath, 'utf8');
    expect(usersContent).toContain('Code generated by sqlc');
    expect(usersContent).toContain('CreateOrUpdateAuthUser');
  });

  it('should pass schema drift and table-level column checks with zero violations', () => {
    const output = execSync('node scripts/lint-schema-drift.mjs', {
      cwd: rootDir,
      encoding: 'utf-8',
    });

    expect(output).toContain('✅ 物理 DDL 基线对齐');
    expect(output).toContain('✅ 零漂移');
    expect(output).toContain('✅ 双写面冻结');
  });
});
